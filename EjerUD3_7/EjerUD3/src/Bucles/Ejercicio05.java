package Bucles;
/**
 * Muestra los número del 320 al 160, contando de 20 en 20 utilizando un bucle while
 * Ejercicio05
 */
public class Ejercicio05 {
    public static void main(String[] args) {
        //declaro la varible
        int i =360;
        
        while (i>=160) {
            System.out.println(i);
            i-=20;
        }
    }
}
