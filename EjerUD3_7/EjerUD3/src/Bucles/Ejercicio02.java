package Bucles;
/**
 * Muestra los números múltiplos de 5 de 0-100 utilizando un bucle while.
 * Ejercicio2
 * @author Andrea
 */
public class Ejercicio02 {
    public static void main(String[] args){
        //variables
        int i =0;

        while (i<=100) {
            System.out.println(i);
            i+=5;
        }
        
    }
}
