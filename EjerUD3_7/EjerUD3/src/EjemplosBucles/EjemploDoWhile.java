package EjemplosBucles;
/**
 * Bucle do-while
 * 
 * @author Andrea
 * EjemploDoWhile
 */
public class EjemploDoWhile {
    public static void main(String[] args) {
        //declaramos las variables
        int i = 1;

        do {
            System.out.println(i);
            i++;
        } while (i<11);
    }
}
